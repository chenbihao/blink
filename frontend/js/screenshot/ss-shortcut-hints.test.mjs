import assert from 'node:assert/strict';
import {bindShortcutHints} from './ss-shortcut-hints.js';
const events = {}, body = {dataset: {}};
const clear = bindShortcutHints({addEventListener(name, handler) { events[name] = handler; }}, body);
let prevented = 0;
const event = key => ({key, preventDefault() { prevented++; }});
events.keydown(event('Alt'));
assert.deepEqual(body.dataset, {altDown: 'true'});
events.keydown({...event('Alt'), repeat: true});
assert.equal(body.dataset.altDown, 'true');
events.keyup(event('Alt'));
assert.deepEqual(body.dataset, {});
const altPrevented = prevented;
events.keydown(event('Control'));
assert.deepEqual(body.dataset, {ctrlDown: 'true'});
assert.equal(prevented, altPrevented, 'Ctrl 不拦截文本默认操作');
events.keydown(event('Alt'));
assert.deepEqual(body.dataset, {altDown: 'true', ctrlDown: 'true'});
events.keyup(event('Control'));
assert.deepEqual(body.dataset, {altDown: 'true'});
events.blur();
assert.deepEqual(body.dataset, {});
events.keydown(event('Control'));
clear();
assert.deepEqual(body.dataset, {}, '会话复用时清理修饰键提示');
console.log('shortcut hints: independent Alt/Ctrl, repeat, keyup, blur and session reset passed');
